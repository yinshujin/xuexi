const B = 'xz-g4a';

/**
 * 写作 四年级上册 practice: routine items plus 拔高 / 创新 items of one knowledge
 * point in the xz4.skills bank (packages/practice/src/banks/xz-g4a.ts).
 * `v` is the knowledge point id without "xz-g4a.", e.g. 'u1.reasons'.
 */
function skills(v: string): PracticeSpec[] {
  return [
    { generatorId: 'xz4.skills', minDifficulty: 1, maxDifficulty: 5, variant: v },
    { generatorId: 'xz4.skills', variant: `${v}#stretch`, tier: 'stretch', minDifficulty: 3, maxDifficulty: 5 },
    { generatorId: 'xz4.skills', variant: `${v}#creative`, tier: 'creative', minDifficulty: 3, maxDifficulty: 5 },
  ];
}

type Task = Omit<WritingTask, 'id'>;

/**
 * A 写作 unit: a 方法 knowledge point (lecture) and a 练笔 knowledge point
 * (lecture, technique and the unit's writing task, id `<unit>.task`).
 */
function writingUnit(index: number, title: string, method: KpInput, practice: KpInput, task: Task): Unit {
  const u = unit(B, index, title, [method, practice]);
  const [, write] = u.knowledgePoints;
  write.writing = { id: `${u.id}.task`, ...task };
  return u;
}

